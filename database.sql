-- 1. Crear la tabla de Memes (incluye soporte para 'lengua')
CREATE TABLE IF NOT EXISTS public.memes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    frase TEXT NOT NULL,
    emocion TEXT NOT NULL CHECK (emocion IN ('boca', 'sonrisa', 'serio', 'guino', 'lengua')),
    imagen_url TEXT NOT NULL,
    autor TEXT DEFAULT 'Comunidad',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Habilitar Seguridad por Fila (Row Level Security - RLS)
ALTER TABLE public.memes ENABLE ROW LEVEL SECURITY;

-- 3. Crear Políticas de Acceso Público (Lectura, Inserción y Eliminación para todos)
DROP POLICY IF EXISTS "Permitir lectura publica de memes" ON public.memes;
CREATE POLICY "Permitir lectura publica de memes" 
ON public.memes FOR SELECT 
TO public 
USING (true);

DROP POLICY IF EXISTS "Permitir subida publica de memes" ON public.memes;
CREATE POLICY "Permitir subida publica de memes" 
ON public.memes FOR INSERT 
TO public 
WITH CHECK (true);

DROP POLICY IF EXISTS "Permitir eliminacion publica de memes" ON public.memes;
CREATE POLICY "Permitir eliminacion publica de memes" 
ON public.memes FOR DELETE 
TO public 
USING (true);

-- 4. Habilitar Tiempo Real (Realtime) para que el catálogo se actualice solo
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'memes'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.memes;
    END IF;
END $$;

